const { writeFile } = require("node:fs/promises");
const path = require("node:path");

function escapeHtml(value) {
  return String(value ?? "").replace(/[&<>"']/g, character => ({
    "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;"
  })[character]);
}

async function main() {
  const apiKey = process.env.NYT_API_KEY;
  if (!apiKey) throw new Error("NYT_API_KEY is not set.");

  const url = "https://api.nytimes.com/svc/search/v2/articlesearch.json?q=New%20York&api-key=" +
    encodeURIComponent(apiKey);
  const response = await fetch(url);

  if (!response.ok) {
    throw new Error("NY Times request failed: " + response.status);
  }

  const data = await response.json();
  if (!data.response || !Array.isArray(data.response.docs)) {
    throw new Error("Unexpected NY Times response format.");
  }

  const docs = data.response.docs.slice(0, 10);
  console.log("NY Times API verified. Articles returned:", data.response.docs.length);

  // Only public article metadata is written. The API key never enters the output HTML.
  const articles = docs.map(article => {
    const title = escapeHtml(article.headline?.main || "Untitled");
    const description = escapeHtml(article.abstract || article.snippet || "No summary available.");
    const link = typeof article.web_url === "string" && article.web_url.startsWith("https://")
      ? '<p><a href="' + escapeHtml(article.web_url) + '" target="_blank" rel="noopener noreferrer">Read at The New York Times</a></p>'
      : "";
    return '<article><h2>' + title + '</h2><p>' + description + '</p>' + link + '</article>';
  }).join("\n");

  const html = [
    "<!DOCTYPE html>",
    '<html lang="en">',
    "<head>",
    '<meta charset="UTF-8">',
    '<meta name="viewport" content="width=device-width, initial-scale=1">',
    "<title>HW8 | NY Times API Results</title>",
    "<style>",
    "body{font:16px/1.6 Arial,sans-serif;max-width:850px;margin:40px auto;padding:0 20px;color:#202124}",
    "article{border-bottom:1px solid #ddd;padding:14px 0}h2{font-size:1.2rem;margin-bottom:6px}",
    "a{color:#1656a6} .note{color:#555;font-size:.9rem}",
    "</style>",
    "</head>",
    "<body>",
    "<h1>New York Times Article Search Results</h1>",
    '<p class="note">Search term: New York. This page was generated by GitHub Actions using a private API key. No API key is published here. Source: The New York Times Article Search API.</p>',
    articles || "<p>No articles returned.</p>",
    '<p><a href="index.html">Back to the interactive search page</a></p>',
    "</body>",
    "</html>"
  ].join("\n");

  await writeFile(path.join(__dirname, "results.html"), html, "utf8");
  console.log("Saved article metadata to HW8/results.html (no API key).");
}

main().catch(error => {
  console.error(error);
  process.exit(1);
});
